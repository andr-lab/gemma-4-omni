#!/usr/bin/env python3
"""Export the installed PyTorch C++/ATen build contract for the native bridge."""
from __future__ import annotations

import argparse
from pathlib import Path

import torch
from torch.utils.cpp_extension import include_paths, library_paths


def make_path_flag(prefix: str, path: str) -> str:
    # The container paths used by the native build contain no whitespace. Keep
    # this explicit so the generated make fragment remains shell-transparent.
    if any(char.isspace() for char in path):
        raise ValueError(f"unsupported whitespace in PyTorch path: {path!r}")
    return f"{prefix}{path}"


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()

    includes = [make_path_flag("-I", path) for path in include_paths()]
    libraries = library_paths()
    library_flags = [make_path_flag("-L", path) for path in libraries]
    # The explicit order is required by the shared ATen operator references;
    # --no-as-needed keeps the CUDA dispatcher registration linked in.
    library_flags += [
        "-Xlinker",
        "--no-as-needed",
        "-ltorch",
        "-ltorch_cpu",
        "-ltorch_cuda",
        "-lc10_cuda",
        "-lc10",
    ]
    rpaths = [item for path in libraries for item in ("-Xlinker", "-rpath", "-Xlinker", path)]
    abi = int(getattr(torch._C, "_GLIBCXX_USE_CXX11_ABI", 0))
    content = "\n".join(
        [
            "# Generated by tools/kernel_gates/export_torch_build_config.py.",
            "# Do not hand-edit; regenerate inside the target PyTorch container.",
            f"TORCH_VERSION := {torch.__version__}",
            f"TORCH_CUDA_VERSION := {torch.version.cuda or ''}",
            f"TORCH_CXXFLAGS := -D_GLIBCXX_USE_CXX11_ABI={abi} {' '.join(includes)}",
            f"TORCH_LDFLAGS := {' '.join(library_flags + rpaths)}",
            "",
        ]
    )
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(content, encoding="utf-8")
    print(content, end="")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
