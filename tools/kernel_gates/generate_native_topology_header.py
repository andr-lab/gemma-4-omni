#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""generate_native_topology_header.py — Generates generated_topology.h from GEMMA4_NATIVE_TOPOLOGY.json.

Phase 0 deliverable adhering strictly to P4-NATIVE Implementation Plan §5.
"""
from __future__ import annotations

import json
from pathlib import Path


def c_float(val: float) -> str:
    s = f"{float(val):.7g}"
    if "." not in s and "e" not in s and "E" not in s:
        s += ".0"
    return f"{s}f"


def main() -> None:
    topo_path = Path("validation/kernel_gates/P4_NATIVE/GEMMA4_NATIVE_TOPOLOGY.json")
    if not topo_path.exists():
        raise FileNotFoundError(f"Missing {topo_path}. Run export_gemma4_native_topology.py first.")

    with open(topo_path, "r", encoding="utf-8") as f:
        data = json.load(f)

    manifest_sha = data["manifest_sha256"]
    ckpt_safetensors_sha = data["checkpoint_files"].get("model.safetensors", "unknown")

    num_layers = data["num_hidden_layers"]
    hidden_size = data["hidden_size"]
    intermediate_size = data["intermediate_size"]
    ple_dim = data["hidden_size_per_layer_input"]
    final_norm_eps = data["final_norm_eps"]
    max_positions = data["max_position_embeddings"]
    canonical_text_block_len = int(data["canonical_text_block_len"])
    canonical_prefix_len = int(data["canonical_prefix_len"])
    canonical_lm_prefill_target_len = int(data["canonical_lm_prefill_target_len"])

    out_dir = Path("native/gemma4_listener")
    out_dir.mkdir(parents=True, exist_ok=True)
    out_header = out_dir / "generated_topology.h"

    max_intermediate = max(l.get("gate_proj_shape", [6144])[0] for l in data["layers"])

    lines = [
        "/* Generated by tools/kernel_gates/generate_native_topology_header.py */",
        "/* DO NOT EDIT MANUALLY. Source of truth is GEMMA4_NATIVE_TOPOLOGY.json */",
        "#ifndef GEMMA4_GENERATED_TOPOLOGY_H",
        "#define GEMMA4_GENERATED_TOPOLOGY_H",
        "",
        "#include <stdint.h>",
        "#include <stdbool.h>",
        "",
        f'#define GEMMA4_TOPOLOGY_MANIFEST_SHA256 "{manifest_sha}"',
        f'#define GEMMA4_CHECKPOINT_SAFELAYERS_SHA256 "{ckpt_safetensors_sha}"',
        "#define GEMMA4_ABI_VERSION 3",
        "",
        f"#define GEMMA4_NUM_LAYERS {num_layers}",
        f"#define GEMMA4_HIDDEN_SIZE {hidden_size}",
        f"#define GEMMA4_INTERMEDIATE_SIZE {intermediate_size}",
        f"#define GEMMA4_MAX_INTERMEDIATE_SIZE {max_intermediate}",
        "#define GEMMA4_NUM_ATTN_HEADS 8",
        "#define GEMMA4_NUM_KV_HEADS 1",
        f"#define GEMMA4_PLE_DIM {ple_dim}",
        f"#define GEMMA4_MAX_POSITION_EMBEDDINGS {max_positions}",
        f"#define GEMMA4_TEXT_BLOCK_LEN {canonical_text_block_len}",
        f"#define GEMMA4_CANONICAL_PREFIX_LEN {canonical_prefix_len}",
        f"#define GEMMA4_CANONICAL_LM_PREFILL_TARGET_LEN {canonical_lm_prefill_target_len}",
        "#define GEMMA4_STREAM_Q_LEN 4",
        f"#define GEMMA4_FINAL_NORM_EPS {c_float(final_norm_eps)}",
        "",
        "typedef enum {",
        "    GEMMA_ATTN_SLIDING = 0,",
        "    GEMMA_ATTN_FULL = 1",
        "} GemmaAttentionType;",
        "",
        "typedef enum {",
        "    GEMMA_ACT_GELU_TANH = 0,",
        "    GEMMA_ACT_SILU = 1",
        "} GemmaActivationType;",
        "",
        "typedef struct {",
        "    uint32_t index;",
        "    GemmaAttentionType attn_type;",
        "    uint32_t head_dim;",
        "    uint32_t intermediate_size;",
        "    uint32_t sliding_window;",
        "    float attn_scaling;",
        "    float rope_base;",
        "    bool is_kv_shared;",
        "    int32_t kv_shared_src_index;",
        "    bool store_full_length_kv;",
        "    float layer_scalar;",
        "    float input_norm_eps;",
        "    float post_attn_norm_eps;",
        "    float pre_ff_norm_eps;",
        "    float post_ff_norm_eps;",
        "    float q_norm_eps;",
        "    float k_norm_eps;",
        "    float v_norm_eps;",
        "    float post_ple_norm_eps;",
        "} GemmaLayerSpec;",
        "",
        f"static const GemmaLayerSpec gemma4_layers[GEMMA4_NUM_LAYERS] = {{",
    ]


    for layer in data["layers"]:
        idx = layer["index"]
        l_type = "GEMMA_ATTN_FULL" if layer["layer_type"] == "full_attention" else "GEMMA_ATTN_SLIDING"
        h_dim = layer["head_dim"]
        inter_size = layer.get("gate_proj_shape", [6144])[0]
        sw = layer["sliding_window"] if layer["sliding_window"] is not None else 0
        scaling = layer["attention_scaling"]
        if layer["layer_type"] == "full_attention":
            rope_base = 1000000.0
        else:
            rope_base = 10000.0
        is_shared = "true" if layer["is_kv_shared_layer"] else "false"
        src_idx = layer["kv_shared_layer_index"] if layer["kv_shared_layer_index"] is not None else -1
        store_full = "true" if layer["store_full_length_kv"] else "false"
        l_scalar = layer["layer_scalar"] if isinstance(layer["layer_scalar"], (int, float)) else 1.0

        in_eps = layer["input_layernorm_eps"]
        post_attn_eps = layer["post_attention_layernorm_eps"]
        pre_ff_eps = layer["pre_feedforward_layernorm_eps"]
        post_ff_eps = layer["post_feedforward_layernorm_eps"]
        q_eps = layer["q_norm_eps"] if layer["q_norm_eps"] is not None else 0.0
        k_eps = layer["k_norm_eps"] if layer["k_norm_eps"] is not None else 0.0
        v_eps = layer["v_norm_eps"] if layer["v_norm_eps"] is not None else 0.0
        ple_eps = layer["post_per_layer_input_norm_eps"] if layer["post_per_layer_input_norm_eps"] is not None else 0.0

        entry = (
            f"    {{{idx:2d}, {l_type}, {h_dim:3d}, {inter_size:5d}, {sw:3d}, {c_float(scaling)}, {c_float(rope_base)}, "
            f"{is_shared}, {src_idx:2d}, {store_full}, {c_float(l_scalar)}, "
            f"{c_float(in_eps)}, {c_float(post_attn_eps)}, {c_float(pre_ff_eps)}, {c_float(post_ff_eps)}, "
            f"{c_float(q_eps)}, {c_float(k_eps)}, {c_float(v_eps)}, {c_float(ple_eps)}}},"
        )
        lines.append(entry)

    lines.extend([
        "};",
        "",
        "#endif /* GEMMA4_GENERATED_TOPOLOGY_H */",
        "",
    ])

    with open(out_header, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))

    print(f"[SUCCESS] Header generated at {out_header}")
    print(f"  Layers: {num_layers}, Hidden: {hidden_size}, Manifest SHA: {manifest_sha}")


if __name__ == "__main__":
    main()
